import { PaperAnalysisResult } from '../types/paper';

export function generateMarkdownReport(analysis: PaperAnalysisResult): string {
  const { paperTitle, authors, publicationYear, institutionOrVenue, analyzedAt, steps } = analysis;
  const { problemDefinition, proposedMethodology, keyFindingsAndMetrics, limitationsAndFutureWork, executiveSummary } = steps;

  return `# Research Paper Analysis: ${paperTitle}

**Authors:** ${authors.join(', ')}  
**Year / Venue:** ${publicationYear || 'N/A'} · ${institutionOrVenue || 'Preprint'}  
**Analysis Generated:** ${new Date(analyzedAt).toLocaleDateString()} via ScholarCoT (Chain-of-Thought Protocol)

---

## 1. PROBLEM DEFINITION

### Central Challenge
${problemDefinition.centralChallenge}

### Open Research Question
*${problemDefinition.openQuestion}*

### Prior Art Limitations
${problemDefinition.baselineLimitations.map((lim) => `- ${lim}`).join('\n')}

---

## 2. PROPOSED METHODOLOGY

### Novel Architecture & Mechanisms
${proposedMethodology.novelArchitecture}

### Mathematical Formulation
${proposedMethodology.mathematicalFormulation}

### Algorithmic & Operational Framework
${proposedMethodology.algorithmicFramework}

### Evaluated Datasets & Benchmarks
${proposedMethodology.datasetsUsed.map((ds) => `- ${ds}`).join('\n')}

---

## 3. KEY FINDINGS & METRICS

### Quantitative Results & Baselines
| Metric Name | Paper Result | Baseline Value | Relative Delta / Gain |
| :--- | :--- | :--- | :--- |
${keyFindingsAndMetrics.quantitativeResults
  .map(
    (row) => `| ${row.metricName} | **${row.paperValue}** | ${row.baselineValue} | \`${row.relativeGain}\` |`
  )
  .join('\n')}

### Baseline Comparisons
${keyFindingsAndMetrics.baselineComparisons}

### Key Breakthroughs
${keyFindingsAndMetrics.keyAchievements.map((ach) => `- ${ach}`).join('\n')}

---

## 4. LIMITATIONS & FUTURE WORK

### Noted Constraints & Assumptions
${limitationsAndFutureWork.notedConstraints.map((c) => `- ${c}`).join('\n')}

### Hardware & Compute Dependencies
${limitationsAndFutureWork.hardwareDependencies}

### Potential Biases & Failure Modes
${limitationsAndFutureWork.potentialBiases.map((b) => `- ${b}`).join('\n')}

### Open Research Trajectories
${limitationsAndFutureWork.openDirections.map((d) => `- ${d}`).join('\n')}

---

## 5. EXECUTIVE SUMMARY (Fast Technical Review)

1. ${executiveSummary[0]}
2. ${executiveSummary[1]}
3. ${executiveSummary[2]}
`;
}

export function generateLaTeXDocument(analysis: PaperAnalysisResult): string {
  const { paperTitle, authors, publicationYear, steps } = analysis;
  const { problemDefinition, proposedMethodology, keyFindingsAndMetrics, limitationsAndFutureWork, executiveSummary } = steps;

  // Escape special LaTeX characters in general text strings (excluding math blocks)
  const esc = (text: string) =>
    (text || '')
      .replace(/&/g, '\\&')
      .replace(/%/g, '\\%')
      .replace(/#/g, '\\#')
      .replace(/_/g, '\\_');

  return `\\documentclass[11pt,a4paper]{article}
\\usepackage[utf8]{inputenc}
\\usepackage{amsmath,amssymb,amsfonts}
\\usepackage{booktabs}
\\usepackage{geometry}
\\usepackage{hyperref}
\\usepackage{microtype}
\\geometry{margin=1in}

\\title{\\textbf{Rigorous Technical Analysis: ${esc(paperTitle)}}}
\\author{${esc(authors.join(', '))}}
\\date{${esc(publicationYear || '2026')} \\quad \\textit{(Generated by ScholarCoT Agent)}}

\\begin{document}

\\maketitle

\\begin{abstract}
\\textbf{Executive Summary (3-Bullet Fast Review):}
\\begin{enumerate}
    \\item ${esc(executiveSummary[0])}
    \\item ${esc(executiveSummary[1])}
    \\item ${esc(executiveSummary[2])}
\\end{enumerate}
\\end{abstract}

\\section{Problem Definition}
\\paragraph{Central Challenge:}
${esc(problemDefinition.centralChallenge)}

\\paragraph{Open Research Question:}
\\textit{${esc(problemDefinition.openQuestion)}}

\\paragraph{Prior Baseline Limitations:}
\\begin{itemize}
${problemDefinition.baselineLimitations.map((l) => `    \\item ${esc(l)}`).join('\n')}
\\end{itemize}

\\section{Proposed Methodology}
\\paragraph{Novel Architecture:}
${esc(proposedMethodology.novelArchitecture)}

\\paragraph{Mathematical Formulation:}
${proposedMethodology.mathematicalFormulation}

\\paragraph{Algorithmic Framework:}
${esc(proposedMethodology.algorithmicFramework)}

\\paragraph{Datasets and Benchmarks:}
\\begin{itemize}
${proposedMethodology.datasetsUsed.map((d) => `    \\item ${esc(d)}`).join('\n')}
\\end{itemize}

\\section{Key Findings \\& Quantitative Metrics}
\\paragraph{Empirical Comparison vs Baselines:}
\\begin{table}[ht]
\\centering
\\caption{Quantitative Evaluation Metrics vs Comparative Baselines}
\\begin{tabular}{llll}
\\toprule
\\textbf{Metric} & \\textbf{Paper Value} & \\textbf{Baseline} & \\textbf{Relative Gain} \\\\
\\midrule
${keyFindingsAndMetrics.quantitativeResults
  .map(
    (row) =>
      `${esc(row.metricName)} & \\textbf{${esc(row.paperValue)}} & ${esc(row.baselineValue)} & ${esc(row.relativeGain)} \\\\`
  )
  .join('\n')}
\\bottomrule
\\end{tabular}
\\end{table}

\\paragraph{Comparative Analysis:}
${esc(keyFindingsAndMetrics.baselineComparisons)}

\\paragraph{Key Achievements:}
\\begin{itemize}
${keyFindingsAndMetrics.keyAchievements.map((a) => `    \\item ${esc(a)}`).join('\n')}
\\end{itemize}

\\section{Limitations \\& Future Work}
\\paragraph{Noted Constraints:}
\\begin{itemize}
${limitationsAndFutureWork.notedConstraints.map((c) => `    \\item ${esc(c)}`).join('\n')}
\\end{itemize}

\\paragraph{Hardware \\& Compute Dependencies:}
${esc(limitationsAndFutureWork.hardwareDependencies)}

\\paragraph{Potential Biases and Failure Modes:}
\\begin{itemize}
${limitationsAndFutureWork.potentialBiases.map((b) => `    \\item ${esc(b)}`).join('\n')}
\\end{itemize}

\\paragraph{Open Research Horizons:}
\\begin{itemize}
${limitationsAndFutureWork.openDirections.map((d) => `    \\item ${esc(d)}`).join('\n')}
\\end{itemize}

\\end{document}
`;
}

export function downloadFile(filename: string, content: string, contentType: string) {
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
